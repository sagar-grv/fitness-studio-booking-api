"""Fitness Studio Booking API - FastAPI application entry point.

Run locally:
    uvicorn app.main:app --reload

Interactive docs (auto-generated by FastAPI):
    http://127.0.0.1:8000/docs
"""

import logging
import time

from fastapi import FastAPI, Request

from .database import Base, engine
from .routers import auth_routes, bookings, classes

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s %(levelname)s %(name)s: %(message)s",
)
logger = logging.getLogger("fitness_studio")

# Create tables on startup (SQLite; swap in Alembic for a production DB).
Base.metadata.create_all(bind=engine)

app = FastAPI(
    title="Fitness Studio Booking API",
    description=(
        "Booking API for a fictional fitness studio. Users sign up and log in "
        "(JWT), then create classes, book slots, and view their bookings. "
        "All class times are stored in IST (Asia/Kolkata)."
    ),
    version="1.0.0",
)


@app.middleware("http")
async def log_requests(request: Request, call_next):
    """Log every request with method, path, status and duration."""
    start = time.perf_counter()
    response = await call_next(request)
    duration_ms = (time.perf_counter() - start) * 1000
    logger.info(
        "%s %s -> %s (%.1f ms)",
        request.method,
        request.url.path,
        response.status_code,
        duration_ms,
    )
    return response


@app.get("/", tags=["health"])
def root():
    return {"status": "ok", "service": "Fitness Studio Booking API"}


app.include_router(auth_routes.router)
app.include_router(classes.router)
app.include_router(bookings.router)
